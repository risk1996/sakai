//! Stub metadata for Python types erased by the binding conversions.

use std::{any::TypeId, fs, path::Path};

use pyo3_stub_gen::{StubInfo, TypeInfo, generate::MemberDef};

use super::{CpuMax, CpusetPartition, IoDeviceCostModel, IoDeviceCostQos, IoDeviceMax, RdmaDeviceMax};

pyo3_stub_gen::derive::gen_type_alias_from_python!(
  "sakai._sakai",
  r#"
import os
import typing

PathArg: typing.TypeAlias = str | bytes | os.PathLike[str] | os.PathLike[bytes]
CgroupKind: typing.TypeAlias = typing.Literal["domain", "domain threaded", "domain invalid", "threaded"]
RdmaDeviceKey: typing.TypeAlias = tuple[str, int | None]
"#
);

/// Generate the Linux extension stub and package exports, retaining erased types.
///
/// Run with the stubs feature on Linux. The stub emits only type declarations;
/// native documentation remains in Rust.
///
/// # Errors
///
/// Returns an error if binding metadata is missing, project configuration cannot
/// be read, or the generated files cannot be written.
pub fn generate_stubs() -> pyo3_stub_gen::Result<()> {
  let mut info = StubInfo::from_pyproject_toml(concat!(env!("CARGO_MANIFEST_DIR"), "/pyproject.toml"))?;
  let mut exceptions =
    info.modules.remove("_sakai").ok_or_else(|| std::io::Error::other("missing exception metadata"))?;
  let module = info.modules.get_mut("sakai._sakai").ok_or_else(|| std::io::Error::other("missing binding metadata"))?;
  for class in exceptions.class.values_mut() {
    class.module = Some("sakai._sakai");
    for base in &mut class.bases {
      if base.name == "builtins.SakaiError" {
        *base = TypeInfo::unqualified("SakaiError");
      }
    }
    if !matches!(class.name, "SakaiError" | "NotCgroupV2Error") {
      class.attrs.push(MemberDef {
        name: "path",
        r#type: TypeInfo::with_module("pathlib.Path", "pathlib".into()),
        doc: "",
        default: None,
        deprecated: None,
      });
    }
    if class.name == "NotSupportedError" {
      for (name, ty) in [("filename", "pathlib.Path"), ("errno", "int | None")] {
        class.attrs.push(MemberDef {
          name,
          r#type: TypeInfo::unqualified(ty),
          doc: "",
          default: None,
          deprecated: None,
        });
      }
    }
  }
  module.class.append(&mut exceptions.class);
  // The generator does not apply type overrides to automatic field getters.
  for (id, names, ty) in [
    (TypeId::of::<CpuMax>(), "quota_ns", "MaxOr[int]"),
    (TypeId::of::<CpuMax>(), "cpu_count", "MaxOr[float]"),
    (TypeId::of::<CpusetPartition>(), "state", "typing.Literal['member', 'root', 'isolated']"),
    (TypeId::of::<IoDeviceCostQos>(), "control", "typing.Literal['auto', 'user']"),
    (TypeId::of::<IoDeviceCostModel>(), "control", "typing.Literal['auto', 'user']"),
    (TypeId::of::<IoDeviceCostModel>(), "model", "typing.Literal['linear']"),
    (TypeId::of::<IoDeviceMax>(), "read_bps write_bps read_iops write_iops", "MaxOr[int]"),
    (TypeId::of::<RdmaDeviceMax>(), "hca_handle hca_object", "MaxOr[int]"),
  ] {
    let class = module.class.get_mut(&id).ok_or_else(|| std::io::Error::other("missing field override class"))?;
    for name in names.split_whitespace() {
      let getter = class
        .getter_setters
        .get_mut(name)
        .and_then(|(getter, _)| getter.as_mut())
        .ok_or_else(|| std::io::Error::other(format!("missing field {}.{name}", class.name)))?;
      getter.r#type = TypeInfo::unqualified(ty);
    }
  }
  // Keep generated declarations compact; native docstrings are checked separately.
  for class in module.class.values_mut() {
    class.doc = "";
    for member in &mut class.attrs {
      member.doc = "";
    }
    for (getter, setter) in class.getter_setters.values_mut() {
      for member in getter.iter_mut().chain(setter.iter_mut()) {
        member.doc = "";
      }
    }
    for method in class.methods.values_mut().flatten() {
      method.doc = "";
    }
  }
  // pyo3-stub-gen has no generic class metadata yet.
  let stub = module.format_with_config(false).replace(
    "@typing.final\nclass MaxOr:",
    "_ValueT = typing.TypeVar(\"_ValueT\", int, float)\n\n@typing.final\nclass MaxOr(typing.Generic[_ValueT]):",
  );
  let package = Path::new(env!("CARGO_MANIFEST_DIR")).join("python/sakai");
  fs::write(package.join("_sakai.pyi"), stub)?;
  // Derive public re-exports from the same class metadata.
  let mut names = module.class.values().map(|class| class.name).collect::<Vec<_>>();
  names.sort_unstable_by_key(|name| name.to_lowercase());
  let exports = names.iter().map(|name| format!("from ._sakai import {name} as {name}")).collect::<Vec<_>>().join("\n");
  fs::write(
    package.join("__init__.py"),
    format!(
      "# Generated by stub_gen; do not edit.\n\"\"\"Read-only cgroup v2 readers. Each method performs a fresh, \
       non-atomic read.\"\"\"\n\nfrom . import _sakai\n{exports}\n\n__all__ = [name for name in dir(_sakai) if not \
       name.startswith(\"_\")]\n"
    ),
  )?;
  Ok(())
}
